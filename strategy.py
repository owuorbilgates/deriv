"""
Strategy Engine Module for Deriv Digit Trading Bot.

Implements the Decoupled Dynamic Match/Differs State Machine with 2-Trade Match Cap:
1. Primary Normal Phase (DIFFERS):
   - Executes DIGITDIFF on statistically cold digits (<= 2.0% occurrence in rolling window).
   - Bets against cold digits that rarely appear.
   - Takes frequent small wins with flat $0.35 stake.
2. Drawdown Recovery Phase (MATCH - Capped at 2 Trades):
   - If a loss occurs in Differs mode, the bot switches to MATCH mode.
   - Quarantines the losing digit in a 10-trade Anti-Revenge Blacklist.
   - Executes DIGITMATCH on hot digits (>= 19.0% occurrence) betting with the streak.
   - Allows up to TWO (2) Match trades with a flat $0.35 stake (ZERO Martingale).
3. State Restoration (Back to DIFFERS):
   - If ANY Match trade WINS (either trade 1 or trade 2): immediately switches back to DIFFERS.
   - If BOTH Match trades LOSE (2-trade cap reached): immediately switches back to DIFFERS to prevent bleeding!
"""

from collections import Counter, deque
from dataclasses import dataclass, field
from decimal import Decimal
from enum import Enum
from typing import Deque, Dict, List, Optional, Tuple
import logging

logger = logging.getLogger("StrategyEngine")


class SignalType(str, Enum):
    """Enumeration of possible strategy outputs."""
    DIGITDIFF = "DIGITDIFF"
    DIGITMATCH = "DIGITMATCH"
    WAIT = "WAIT"


@dataclass(frozen=True)
class TickData:
    """Individual market tick representation."""
    symbol: str
    quote: float
    pip_size: int
    last_digit: int
    epoch: int


@dataclass(frozen=True)
class StrategySignal:
    """Trading signal generated by the strategy engine."""
    signal_type: SignalType
    predicted_barrier: int            # Specific target digit (0-9)
    confidence: float                 # Confidence score (0.0 to 1.0)
    reason: str                       # Descriptive rationale for logs and audits
    distribution: Dict[int, float] = field(default_factory=dict)  # Digit 0-9 percentage breakdown


class StrategyEngine:
    """
    Quantitative Strategy Engine with 2-Trade Capped Match/Differs State Machine.
    """

    def __init__(
        self,
        buffer_size: int = 1000,
        differs_cold_threshold: Optional[float] = None,
        match_hot_threshold: Optional[float] = None,
        strategy_mode: str = "DIFFERS",
        blacklist_duration_trades: int = 10,
        dynamic_mode_switch: bool = False,
        max_match_attempts: int = 2,
        threshold_percent: Optional[float] = None
    ):
        """
        Initialize decoupled strategy engine.
        
        Args:
            buffer_size: Rolling window size (default: 1000 ticks to match Deriv platform).
            differs_cold_threshold: Max occurrence % for cold digit in DIFFERS mode (default: 9.0% for >=500 ticks, 2.0% for <500).
            match_hot_threshold: Min occurrence % for hot digit in MATCH mode (default: 11.5% for >=500 ticks, 19.0% for <500).
            strategy_mode: Starting mode ("DIFFERS" or "MATCH").
            blacklist_duration_trades: Number of trades to quarantine a losing digit.
            dynamic_mode_switch: If True, switches to MATCH on loss, and back to DIFFERS on win or 2 losses.
            max_match_attempts: Maximum number of trades permitted in MATCH mode before reverting to DIFFERS (default: 2).
            threshold_percent: Legacy parameter (maps to match_hot_threshold if provided).
        """
        self.buffer_size = buffer_size
        
        # Adaptive thresholds: calibrated automatically to window sample size
        if differs_cold_threshold is not None:
            self.differs_cold_threshold = differs_cold_threshold
        else:
            self.differs_cold_threshold = 9.0 if buffer_size >= 500 else 2.0
            
        if threshold_percent is not None:
            self.match_hot_threshold = threshold_percent
        elif match_hot_threshold is not None:
            self.match_hot_threshold = match_hot_threshold
        else:
            self.match_hot_threshold = 11.5 if buffer_size >= 500 else 19.0
            
        # Legacy alias for backward compatibility
        self.threshold_percent = self.match_hot_threshold
        
        self.strategy_mode = strategy_mode.upper()
        self.blacklist_duration = blacklist_duration_trades
        dynamic_mode_switch = dynamic_mode_switch
        self.dynamic_mode_switch = dynamic_mode_switch
        self.max_match_attempts = max_match_attempts
        
        # Counter for trades executed while in MATCH mode
        self.match_attempts: int = 0
        
        self.tick_history: Deque[TickData] = deque(maxlen=buffer_size)
        
        # Anti-Revenge Digit Blacklist: {digit: remaining_trades_in_quarantine}
        self.digit_blacklist: Dict[int, int] = {}

    @staticmethod
    def extract_last_digit(quote: float, pip_size: int = 2) -> int:
        """
        Extract exact last decimal digit via Decimal to avoid float truncation or rounding errors.
        Correctly handles trailing zeros and fractional/integer pip sizes (e.g. 0.01 -> 2, 3.0 -> 3).
        """
        if pip_size is None or pip_size < 0:
            pip_size = 2
        elif 0 < pip_size < 1:
            pip_size = abs(Decimal(str(pip_size)).as_tuple().exponent)
        else:
            pip_size = int(pip_size)

        d = Decimal(str(quote))
        formatted_price = f"{d:.{pip_size}f}"
        return int(formatted_price[-1])

    def seed_history(self, ticks: List[TickData]) -> None:
        """Pre-seed the rolling history with historical ticks."""
        self.tick_history.clear()
        for t in ticks[-self.buffer_size:]:
            self.tick_history.append(t)
        logger.info(f"StrategyEngine pre-seeded with {len(self.tick_history)} historical ticks.")

    def clear_history(self) -> None:
        """Clear tick history buffer when switching markets."""
        self.tick_history.clear()

    def on_trade_completed(self, status: str, barrier: int) -> None:
        """
        Update state machine and digit blacklist upon trade completion.
        
        1. Decrements active blacklist counters.
        2. If status == 'lost': quarantines the barrier digit for blacklist_duration trades.
        3. Dynamic State Machine Transitions (2-Trade Match Cap Protocol):
           - In DIFFERS: On 1 loss -> switches to MATCH (match_attempts = 0).
           - In MATCH:
             - If WON on trade 1 or 2 -> switches back to DIFFERS immediately!
             - If LOST on trade 1 -> increments counter to 1, remains in MATCH for trade 2.
             - If LOST on trade 2 -> reaches 2-trade cap, switches back to DIFFERS immediately!
        """
        # Decrement existing blacklists
        expired_digits = []
        for d in list(self.digit_blacklist.keys()):
            self.digit_blacklist[d] -= 1
            if self.digit_blacklist[d] <= 0:
                expired_digits.append(d)
        for d in expired_digits:
            del self.digit_blacklist[d]
            logger.info(f"🔓 [UNLOCKED] Digit [{d}] has completed cooldown and is removed from blacklist.")

        # If trade lost, quarantine the barrier digit
        if status == "lost":
            self.digit_blacklist[barrier] = self.blacklist_duration
            logger.warning(
                f"🚫 [BLACKLIST PROTOCOL] Loss on Digit [{barrier}]! Digit quarantined for the "
                f"next {self.blacklist_duration} trades to prevent revenge trading into a hot cluster."
            )

        # Dynamic State Machine Transitions with 2-Trade Match Cap
        if self.dynamic_mode_switch:
            if self.strategy_mode == "DIFFERS" and status == "lost":
                self.match_attempts = 0
                logger.warning(
                    f"🔄 [STRATEGY PIVOT: DIFFERS -> MATCH] Differs contract lost! "
                    f"Switching to MATCH recovery mode (Max {self.max_match_attempts} trades, Flat stake $0.35, No Martingale)."
                )
                self.strategy_mode = "MATCH"
            elif self.strategy_mode == "MATCH":
                self.match_attempts += 1
                if status == "won":
                    logger.info(
                        f"🎉 [RECOVERY COMPLETE: MATCH -> DIFFERS] Match contract WON on trade {self.match_attempts}/{self.max_match_attempts}! "
                        f"Loss recovered with positive payoff. Switching back to primary DIFFERS mode."
                    )
                    self.match_attempts = 0
                    self.strategy_mode = "DIFFERS"
                else:
                    if self.match_attempts >= self.max_match_attempts:
                        logger.warning(
                            f"⚠️ [MATCH CAP REACHED: MATCH -> DIFFERS] Reached 2-trade limit ({self.match_attempts}/{self.max_match_attempts}) in Match mode without win. "
                            f"Capping drawdown and switching back to primary DIFFERS mode."
                        )
                        self.match_attempts = 0
                        self.strategy_mode = "DIFFERS"
                    else:
                        logger.info(
                            f"ℹ️ [MATCH TRADE {self.match_attempts}/{self.max_match_attempts}] Match trade lost. "
                            f"1 attempt remaining before returning to DIFFERS mode."
                        )

    def on_new_tick(self, symbol: str, quote: float, pip_size: int, epoch: int) -> Tuple[TickData, StrategySignal]:
        """Process incoming tick, update history, and evaluate strategy."""
        last_digit = self.extract_last_digit(quote, pip_size)
        tick = TickData(
            symbol=symbol,
            quote=quote,
            pip_size=pip_size,
            last_digit=last_digit,
            epoch=epoch
        )
        self.tick_history.append(tick)
        signal = self.evaluate_strategy(self.tick_history)
        return tick, signal

    def evaluate_strategy(self, tick_history: Deque[TickData]) -> StrategySignal:
        """
        Evaluate Digit Distribution over the rolling window according to decoupled triggers:
        - DIFFERS Mode: Bet DIGITDIFF on cold digits (occurrence <= differs_cold_threshold, default <= 2.0%).
        - MATCH Mode: Bet DIGITMATCH on hot digits (occurrence >= match_hot_threshold, default >= 19.0%).
        """
        mode_tag = (
            f"MATCH ({self.match_attempts + 1}/{self.max_match_attempts})"
            if self.strategy_mode == "MATCH"
            else "DIFFERS"
        )

        if len(tick_history) < self.buffer_size:
            return StrategySignal(
                signal_type=SignalType.WAIT,
                predicted_barrier=0,
                confidence=0.0,
                reason=f"[{mode_tag}] Accumulating tick history ({len(tick_history)}/{self.buffer_size} ticks required)"
            )

        digits: List[int] = [t.last_digit for t in tick_history]
        total_ticks = len(digits)
        freq = Counter(digits)

        # Compute occurrence percentages for all digits 0-9
        distribution: Dict[int, float] = {}
        for d in range(10):
            distribution[d] = round((freq.get(d, 0) / total_ticks) * 100.0, 1)

        # ---------------------------------------------------------------------
        # 1. PRIMARY NORMAL PHASE: DIFFERS (Bet on COLD digits <= 2.0%)
        # ---------------------------------------------------------------------
        if self.strategy_mode == "DIFFERS":
            # Rank digits from least frequent to most frequent (coldest first)
            cold_ranked = sorted(range(10), key=lambda d: (freq.get(d, 0), d))
            
            target_digit = None
            target_pct = 0.0
            target_count = 0

            for digit in cold_ranked:
                count = freq.get(digit, 0)
                pct = (count / total_ticks) * 100.0
                if pct > self.differs_cold_threshold:
                    break  # Remaining digits exceed cold threshold

                if digit in self.digit_blacklist:
                    rem = self.digit_blacklist[digit]
                    logger.debug(
                        f"[DIFFERS] Skipping cold digit [{digit}] ({pct:.1f}%): quarantined in blacklist ({rem} trades left)."
                    )
                    continue

                target_digit = digit
                target_pct = pct
                target_count = count
                break

            if target_digit is not None:
                confidence = max(0.90, round(1.0 - (target_pct / 100.0), 2))
                return StrategySignal(
                    signal_type=SignalType.DIGITDIFF,
                    predicted_barrier=target_digit,
                    confidence=confidence,
                    reason=(
                        f"🎯 [DIFFERS COLD] Digit '{target_digit}' is cold ({target_count}/{total_ticks}, "
                        f"{target_pct:.1f}% <= {self.differs_cold_threshold:.1f}%, not blacklisted). "
                        f"Betting on DIGITDIFF."
                    ),
                    distribution=distribution
                )

            # Check if coldest candidate was blacklisted
            coldest_d = cold_ranked[0]
            coldest_cnt = freq.get(coldest_d, 0)
            coldest_pct = (coldest_cnt / total_ticks) * 100.0
            if coldest_pct <= self.differs_cold_threshold and coldest_d in self.digit_blacklist:
                rem = self.digit_blacklist[coldest_d]
                return StrategySignal(
                    signal_type=SignalType.WAIT,
                    predicted_barrier=coldest_d,
                    confidence=0.0,
                    reason=(
                        f"[DIFFERS] Coldest Digit [{coldest_d}] ({coldest_pct:.1f}%) is quarantined in Anti-Revenge Blacklist "
                        f"({rem} trades left). Waiting for unquarantined cold digit."
                    ),
                    distribution=distribution
                )

            return StrategySignal(
                signal_type=SignalType.WAIT,
                predicted_barrier=coldest_d,
                confidence=0.0,
                reason=(
                    f"[DIFFERS] No cold digit detected: Coldest Digit '{coldest_d}' at "
                    f"{coldest_pct:.1f}% > {self.differs_cold_threshold:.1f}% threshold."
                ),
                distribution=distribution
            )

        # ---------------------------------------------------------------------
        # 2. DRAWDOWN RECOVERY PHASE: MATCH (Bet on HOT digits >= 19.0%)
        # ---------------------------------------------------------------------
        else:
            # Rank digits from most frequent to least frequent (hottest first)
            hot_ranked = sorted(range(10), key=lambda d: (-freq.get(d, 0), d))

            target_digit = None
            target_pct = 0.0
            target_count = 0

            for digit in hot_ranked:
                count = freq.get(digit, 0)
                pct = (count / total_ticks) * 100.0
                if pct < self.match_hot_threshold:
                    break  # Remaining digits do not meet hot threshold

                if digit in self.digit_blacklist:
                    rem = self.digit_blacklist[digit]
                    logger.debug(
                        f"[{mode_tag}] Skipping hot digit [{digit}] ({pct:.1f}%): quarantined in blacklist ({rem} trades left)."
                    )
                    continue

                target_digit = digit
                target_pct = pct
                target_count = count
                break

            if target_digit is not None:
                confidence = min(0.99, round(target_pct / 100.0, 2))
                return StrategySignal(
                    signal_type=SignalType.DIGITMATCH,
                    predicted_barrier=target_digit,
                    confidence=confidence,
                    reason=(
                        f"🔥 [{mode_tag} RECOVERY] Digit '{target_digit}' is hot ({target_count}/{total_ticks}, "
                        f"{target_pct:.1f}% >= {self.match_hot_threshold:.1f}%). "
                        f"Betting WITH streak on DIGITMATCH (Flat $0.35, No Martingale)."
                    ),
                    distribution=distribution
                )

            # Check if hottest candidate was blacklisted
            hottest_d = hot_ranked[0]
            hottest_cnt = freq.get(hottest_d, 0)
            hottest_pct = (hottest_cnt / total_ticks) * 100.0
            if hottest_pct >= self.match_hot_threshold and hottest_d in self.digit_blacklist:
                rem = self.digit_blacklist[hottest_d]
                return StrategySignal(
                    signal_type=SignalType.WAIT,
                    predicted_barrier=hottest_d,
                    confidence=0.0,
                    reason=(
                        f"[{mode_tag}] Hottest Digit [{hottest_d}] ({hottest_pct:.1f}%) is quarantined in Anti-Revenge Blacklist "
                        f"({rem} trades left). Avoiding revenge trading."
                    ),
                    distribution=distribution
                )

            return StrategySignal(
                signal_type=SignalType.WAIT,
                predicted_barrier=hottest_d,
                confidence=0.0,
                reason=(
                    f"[{mode_tag}] No hot digit detected: Highest Digit '{hottest_d}' at "
                    f"{hottest_pct:.1f}% < {self.match_hot_threshold:.1f}% threshold."
                ),
                distribution=distribution
            )

    @staticmethod
    def format_deriv_percentage(pct: float) -> str:
        """
        Format percentage string identically to the Deriv platform Last Digit Prediction widget.
        E.g.: 9.0 -> '9%', 10.2 -> '10.2%', 12.3 -> '12.3%'.
        """
        rounded = round(pct, 1)
        if rounded.is_integer():
            return f"{int(rounded)}%"
        return f"{rounded:.1f}%"

    def get_distribution_summary(self) -> str:
        """Return formatted distribution summary showing active mode and blacklist."""
        mode_tag = (
            f"MATCH ({self.match_attempts + 1}/{self.max_match_attempts})"
            if self.strategy_mode == "MATCH"
            else "DIFFERS"
        )
        if not self.tick_history:
            return f"[{mode_tag}] No ticks recorded yet"
        
        digits = [t.last_digit for t in self.tick_history]
        total = len(digits)
        freq = Counter(digits)
        
        items = []
        for d in range(10):
            cnt = freq.get(d, 0)
            pct = (cnt / total) * 100.0
            mark = ""
            if d in self.digit_blacklist:
                mark = f"(BL:{self.digit_blacklist[d]})"
            elif self.strategy_mode == "DIFFERS" and pct <= self.differs_cold_threshold:
                mark = "*"  # Cold trigger candidate for Differs
            elif self.strategy_mode == "MATCH" and pct >= self.match_hot_threshold:
                mark = "*"  # Hot trigger candidate for Match
            items.append(f"{d}:{self.format_deriv_percentage(pct)}{mark}")
            
        bl_info = ""
        if self.digit_blacklist:
            bl_str = ", ".join([f"{k} ({v} left)" for k, v in self.digit_blacklist.items()])
            bl_info = f" | Blacklist: [{bl_str}]"
            
        return f"[{mode_tag}] Digits ({total} ticks): [{' '.join(items)}]{bl_info}"

    def get_deriv_prediction_table(self, symbol: str = "") -> str:
        """
        Generate a formatted prediction table matching Deriv's Last Digit Prediction widget.
        Displays count and percentage for digits 0-9 with cold/hot indicator tags.
        """
        if not self.tick_history:
            return f"No tick history available for {symbol} (Window: {self.buffer_size} ticks)"

        digits = [t.last_digit for t in self.tick_history]
        total = len(digits)
        freq = Counter(digits)

        sym_tag = f" - {symbol}" if symbol else ""
        lines = [
            f"============================================================",
            f"📊 DERIV LAST DIGIT PREDICTION ({total}/{self.buffer_size} Ticks){sym_tag}",
            f"============================================================",
            f" Digit | Occurrences | Percentage | Status",
            f"------------------------------------------------------------"
        ]

        for d in range(10):
            cnt = freq.get(d, 0)
            pct = (cnt / total) * 100.0 if total > 0 else 0.0
            pct_str = self.format_deriv_percentage(pct)

            status = ""
            if d in self.digit_blacklist:
                status = f"🚫 Quarantined ({self.digit_blacklist[d]} trades left)"
            elif self.strategy_mode == "DIFFERS" and pct <= self.differs_cold_threshold:
                status = f"❄️  COLD (<= {self.differs_cold_threshold:.1f}%) -> DIFFERS TARGET"
            elif self.strategy_mode == "MATCH" and pct >= self.match_hot_threshold:
                status = f"🔥 HOT (>= {self.match_hot_threshold:.1f}%) -> MATCH TARGET"
            elif pct <= self.differs_cold_threshold:
                status = f"❄️  COLD (<= {self.differs_cold_threshold:.1f}%)"
            elif pct >= self.match_hot_threshold:
                status = f"🔥 HOT (>= {self.match_hot_threshold:.1f}%)"

            lines.append(f"   {d}   |    {cnt:>4}     |    {pct_str:>6}   | {status}")

        lines.append(f"============================================================")
        return "\n".join(lines)
