"""
Strategy Engine Module for Deriv Digit Trading Bot.

Handles tick history ingestion, high-precision digit extraction, and
mathematical pattern recognition to output signals: DIGITMATCH, DIGITDIFF, or WAIT.
"""

from collections import Counter, deque
from dataclasses import dataclass
from enum import Enum
from typing import Deque, List, Optional, Tuple
import logging

logger = logging.getLogger("StrategyEngine")


class SignalType(str, Enum):
    """Enumeration of possible strategy outputs."""
    DIGITMATCH = "DIGITMATCH"
    DIGITDIFF = "DIGITDIFF"
    WAIT = "WAIT"


@dataclass(frozen=True)
class TickData:
    """Individual market tick representation."""
    symbol: str
    quote: float
    pip_size: int
    last_digit: int
    epoch: int


@dataclass(frozen=True)
class StrategySignal:
    """Trading signal generated by the strategy engine."""
    signal_type: SignalType
    predicted_barrier: int  # Specific target digit (0-9)
    confidence: float       # Confidence score (0.0 to 1.0)
    reason: str             # Descriptive rationale for logs and audits


class StrategyEngine:
    """
    Modular quantitative strategy engine for Digit Match / Digit Differs.
    
    Maintains a rolling window of recent market ticks and evaluates
    pattern recognition rules against recent decimal digits.
    """

    def __init__(self, buffer_size: int = 50):
        """
        Initialize strategy engine.
        
        Args:
            buffer_size: Max number of recent ticks to maintain in memory.
        """
        self.buffer_size = buffer_size
        self.tick_history: Deque[TickData] = deque(maxlen=buffer_size)

    @staticmethod
    def extract_last_digit(quote: float, pip_size: int = 2) -> int:
        """
        Extract the exact last decimal digit of a price quote.
        
        Crucial Quantitative Note:
        Deriv quotes have strict decimal precision (pip_size).
        Standard float-to-string conversions like str(1245.50) will truncate trailing
        zeros into "1245.5", resulting in an erroneous digit '5' instead of '0'.
        Using fixed-width decimal formatting guarantees precision.
        """
        if pip_size is None or pip_size < 0:
            pip_size = 2
            
        formatted_price = f"{quote:.{pip_size}f}"
        last_char = formatted_price[-1]
        return int(last_char)

    def on_new_tick(self, symbol: str, quote: float, pip_size: int, epoch: int) -> Tuple[TickData, StrategySignal]:
        """
        Process an incoming live tick, update internal history, and evaluate strategy.
        
        Args:
            symbol: Underlying instrument (e.g. 'R_100')
            quote: Latest price quote
            pip_size: Market decimal precision
            epoch: Timestamp of the tick
            
        Returns:
            Tuple of (TickData, StrategySignal)
        """
        last_digit = self.extract_last_digit(quote, pip_size)
        tick = TickData(
            symbol=symbol,
            quote=quote,
            pip_size=pip_size,
            last_digit=last_digit,
            epoch=epoch
        )
        self.tick_history.append(tick)
        
        # Evaluate current strategy rules
        signal = self.evaluate_strategy(self.tick_history)
        return tick, signal

    def evaluate_strategy(self, tick_history: Deque[TickData]) -> StrategySignal:
        """
        ISOLATED STRATEGY EVALUATION FUNCTION (The Brain).
        
        Analyzes the rolling tick history and returns DIGITMATCH, DIGITDIFF, or WAIT.
        
        Args:
            tick_history: Deque containing recent TickData items.
            
        Returns:
            StrategySignal containing signal_type, predicted_barrier (0-9), confidence, and reason.
        """
        min_required_ticks = 5
        if len(tick_history) < min_required_ticks:
            return StrategySignal(
                signal_type=SignalType.WAIT,
                predicted_barrier=0,
                confidence=0.0,
                reason=f"Insufficient tick history ({len(tick_history)}/{min_required_ticks})"
            )

        # Extract recent digits as a clean list of integers
        digits: List[int] = [t.last_digit for t in tick_history]
        last_5_digits = digits[-5:]
        last_digit = digits[-1]
        
        # =====================================================================
        # === USER STRATEGY LOGIC START (CUSTOM PATTERN RECOGNITION RULES) ===
        # =====================================================================
        # You can modify or replace the rules below with your own mathematical
        # formulas, machine learning signals, or statistical anomaly detectors.
        
        # ---------------------------------------------------------------------
        # PATTERN RULE 1: Consecutive Digit Repeat Anomaly (DIGITDIFF)
        # Rationale: If the exact same digit appears 2 consecutive times,
        # the statistical probability of a 3rd identical digit on synthetic
        # RNG volatility indices is extremely low (~1.0%).
        # We predict DIGITDIFF on that repeating digit.
        # ---------------------------------------------------------------------
        if len(digits) >= 2 and digits[-1] == digits[-2]:
            repeated_digit = digits[-1]
            return StrategySignal(
                signal_type=SignalType.DIGITDIFF,
                predicted_barrier=repeated_digit,
                confidence=0.92,
                reason=(
                    f"Consecutive repeat detected: Digit '{repeated_digit}' appeared twice in a row "
                    f"([..., {digits[-2]}, {digits[-1]}]). High probability of Differs."
                )
            )

        # ---------------------------------------------------------------------
        # PATTERN RULE 2: Digit Over-Frequency Anomaly (DIGITDIFF)
        # Rationale: If a digit appears 3 or more times in the last 5 ticks,
        # it is severely over-represented. Mean-reversion implies it will diff.
        # ---------------------------------------------------------------------
        freq_last_5 = Counter(last_5_digits)
        most_common_digit, count = freq_last_5.most_common(1)[0]
        if count >= 3:
            return StrategySignal(
                signal_type=SignalType.DIGITDIFF,
                predicted_barrier=most_common_digit,
                confidence=0.88,
                reason=(
                    f"Over-frequency anomaly: Digit '{most_common_digit}' appeared {count}/5 times "
                    f"in recent ticks {last_5_digits}."
                )
            )

        # ---------------------------------------------------------------------
        # PATTERN RULE 3: Cold / Dormant Digit Reversion (DIGITMATCH - Optional)
        # Rationale: If a digit has not appeared in 25+ ticks, in some mean-
        # reversion models traders look for a match. (Disabled by default,
        # uncomment if your strategy trades Digit Matches on cold digits).
        # ---------------------------------------------------------------------
        # if len(digits) >= 25:
        #     all_digits = set(range(10))
        #     recent_set = set(digits[-25:])
        #     missing_digits = all_digits - recent_set
        #     if missing_digits:
        #         cold_digit = sorted(list(missing_digits))[0]
        #         return StrategySignal(
        #             signal_type=SignalType.DIGITMATCH,
        #             predicted_barrier=cold_digit,
        #             confidence=0.15,  # Match payout is ~9x, lower raw confidence
        #             reason=f"Cold digit pattern: Digit '{cold_digit}' has not appeared in 25 ticks."
        #         )

        # =====================================================================
        # === USER STRATEGY LOGIC END =========================================
        # =====================================================================

        # Default state when no statistical anomaly is recognized
        return StrategySignal(
            signal_type=SignalType.WAIT,
            predicted_barrier=0,
            confidence=0.0,
            reason=f"No edge detected in last 5 digits: {last_5_digits}"
        )

    def get_digits_summary(self) -> str:
        """Return a formatted string of the most recent digits for logging."""
        if not self.tick_history:
            return "No ticks recorded yet"
        recent = [str(t.last_digit) for t in list(self.tick_history)[-10:]]
        return f"Recent [{len(recent)}]: {' '.join(recent)}"
